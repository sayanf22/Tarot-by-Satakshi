// Writes a strict Content-Security-Policy for every exported page into out/_headers.
// Next.js puts small inline <script> blocks in each page; instead of allowing all
// inline scripts ('unsafe-inline'), each page's blocks are hashed (SHA-256) and only
// those exact scripts may run. Outside scripts are limited to Razorpay Checkout and
// Cloudflare Turnstile. Runs after `next build` (see package.json).
import { createHash } from "node:crypto";
import { appendFile, readdir, readFile } from "node:fs/promises";
import { join, relative, sep } from "node:path";

const OUT = "out";
const LINE_LIMIT = 2000; // Cloudflare _headers limit per line

async function htmlFiles(dir) {
  const out = [];
  for (const e of await readdir(dir, { withFileTypes: true })) {
    const full = join(dir, e.name);
    if (e.isDirectory()) out.push(...(await htmlFiles(full)));
    else if (e.name.endsWith(".html")) out.push(full);
  }
  return out;
}

function urlFor(file) {
  const rel = relative(OUT, file)
    .split(sep)
    .join("/")
    .replace(/\.html$/, "");
  if (rel === "index") return "/";
  if (rel === "404" || rel === "_not-found") return null; // served for unknown URLs; covered by /*
  return `/${rel.replace(/\/index$/, "")}`;
}

function policy(hashes) {
  return [
    "default-src 'self'",
    `script-src 'self' ${hashes.join(" ")} https://*.razorpay.com https://challenges.cloudflare.com`,
    "style-src 'self' 'unsafe-inline'",
    "img-src 'self' data: blob: https://*.razorpay.com",
    "font-src 'self'",
    "connect-src 'self' https://*.razorpay.com https://challenges.cloudflare.com",
    "frame-src https://*.razorpay.com https://challenges.cloudflare.com",
    "form-action 'self' https://*.razorpay.com",
    "base-uri 'self'",
    "object-src 'none'",
    "frame-ancestors 'none'",
    "upgrade-insecure-requests",
  ].join("; ");
}

const rules = [];
for (const file of await htmlFiles(OUT)) {
  const url = urlFor(file);
  if (!url) continue;
  const html = await readFile(file, "utf8");
  const hashes = new Set();
  for (const m of html.matchAll(/<script(?![^>]*\bsrc=)[^>]*>([\s\S]*?)<\/script>/g)) {
    hashes.add(`'sha256-${createHash("sha256").update(m[1], "utf8").digest("base64")}'`);
  }
  const line = `  Content-Security-Policy: ${policy([...hashes])}`;
  if (line.length > LINE_LIMIT)
    throw new Error(`csp: policy for ${url} is ${line.length} characters (limit ${LINE_LIMIT})`);
  rules.push(`${url}\n${line}\n`);
}

await appendFile(
  join(OUT, "_headers"),
  `\n# Generated by scripts/csp.mjs: per-page script hashes.\n${rules.join("\n")}`,
);
console.log(`csp: wrote policies for ${rules.length} pages`);
